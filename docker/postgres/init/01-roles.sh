#!/bin/sh
set -eu

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE vault_app LOGIN PASSWORD '${VAULT_APP_DB_PASSWORD}' NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE;
CREATE DATABASE vault_test OWNER vault;
GRANT CONNECT ON DATABASE vault TO vault_app;
GRANT CONNECT ON DATABASE vault_test TO vault_app;
SQL

for db in vault vault_test; do
  psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$db" <<SQL
CREATE EXTENSION IF NOT EXISTS vector;
GRANT USAGE ON SCHEMA public TO vault_app;
ALTER DEFAULT PRIVILEGES FOR ROLE vault IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO vault_app;
ALTER DEFAULT PRIVILEGES FOR ROLE vault IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO vault_app;
SQL
done
